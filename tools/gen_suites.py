"""Generate one sequential TestNG suite per system: suites/<system>.xml.

Blocks, in order: E2E (registered classes) -> Regression (known-bug checks) -> one block per module.
Module order follows the system's legacy "order_from" suites (if any), then module name, so
lifecycle-dependent classes keep their required order. Output depends only on source files, so it is
reproducible without local run history.

Usage: python tools/gen_suites.py
"""

import re
import sys
from xml.sax.saxutils import escape, quoteattr

from regression import regression_classes
from systems import GENERATED_SUITE_ROOT, LEGACY_SUITE_ROOT, SYSTEMS, fqcn
from testsource import discover


def _legacy_order(system):
    """Class and package names in the order they appear in the legacy suites."""
    order = []
    for relative in SYSTEMS[system]["order_from"]:
        path = LEGACY_SUITE_ROOT / relative
        if not path.is_file():
            continue
        for kind, name in re.findall(r'<(class|package)\s+name="([^"]+)"', path.read_text(encoding="utf-8")):
            order.append((kind, name.rstrip(".*")))
    return order


def ordered(system, entries):
    """Entries sorted by first match in the legacy order, then by module and class name."""
    order = _legacy_order(system)

    def rank(entry):
        for index, (kind, name) in enumerate(order):
            if (kind == "class" and entry["class"] == name) or (kind == "package" and entry["class"].startswith(name + ".")):
                return (index, entry["module"], entry["class"])
        return (len(order), entry["module"], entry["class"])

    return sorted(entries, key=rank)


def module_title(system, module):
    return SYSTEMS[system].get("modules", {}).get(module, "Module " + module)


def plan(system, entries, include_excluded=False):
    """[(block name, [class names])] for the whole-suite run of one system."""
    excluded = set() if include_excluded else {fqcn(name) for name in SYSTEMS[system]["exclude"]}
    known = {e["class"] for e in entries}
    e2e = [fqcn(name) for name in SYSTEMS[system]["e2e"] if fqcn(name) in known]
    regression = [name for name in regression_classes(system, entries) if name not in e2e]
    used = set(e2e) | set(regression) | excluded
    blocks = []
    if e2e:
        blocks.append(("E2E", e2e))
    if regression:
        blocks.append(("Regression", regression))
    modules = {}
    for entry in ordered(system, entries):
        if entry["class"] in used:
            continue
        modules.setdefault(entry["module"], []).append(entry["class"])
    blocks += [(module_title(system, module), classes) for module, classes in modules.items()]
    return blocks


def suite_xml(suite_name, blocks, comment=None):
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<!DOCTYPE suite SYSTEM "https://testng.org/testng-1.0.dtd">']
    if comment:
        lines.append("<!-- " + escape(comment) + " -->")
    lines.append("<suite name=%s verbose=\"1\" parallel=\"false\" configfailurepolicy=\"continue\">" % quoteattr(suite_name))
    for block, classes in blocks:
        lines.append("    <test name=%s preserve-order=\"true\">" % quoteattr(block))
        lines.append("        <classes>")
        lines += ["            <class name=%s/>" % quoteattr(name) for name in classes]
        lines.append("        </classes>")
        lines.append("    </test>")
    lines.append("</suite>")
    return "\n".join(lines) + "\n"


def main():
    GENERATED_SUITE_ROOT.mkdir(exist_ok=True)
    for system, entries in discover().items():
        if not entries:
            print("ERROR: no test classes discovered for system " + system, file=sys.stderr)
            return 1
        blocks = plan(system, entries)
        xml = suite_xml(SYSTEMS[system]["title"], blocks,
                        "GENERATED by tools/gen_suites.py - do not edit. Run: mvn test "
                        "-Dsurefire.suiteXmlFiles=suites/%s.xml -Dactive.system=%s" % (system, system))
        path = GENERATED_SUITE_ROOT / (system + ".xml")
        path.write_text(xml, encoding="utf-8", newline="\n")
        print("%s: %d classes in %d blocks -> %s" % (system, sum(len(c) for _, c in blocks), len(blocks),
                                                     path.relative_to(path.parent.parent).as_posix()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
